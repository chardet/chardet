#!/usr/bin/env python
"""Generate ``src/chardet/_unicode_scripts.py`` from the Unicode ``Scripts.txt``.

The table gives the Script property of every code point in the Basic
Multilingual Plane, as runs of equal value.  It is generated from one
pinned Unicode version, not read from :mod:`unicodedata`, so every Python
version chardet supports classifies the same bytes the same way.

Usage::

    curl -O https://www.unicode.org/Public/17.0.0/ucd/Scripts.txt
    uv run python scripts/generate_unicode_scripts.py Scripts.txt \
        > src/chardet/_unicode_scripts.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

_BMP_END = 0x10000
_VERSION = re.compile(r"^# Scripts-(\d+\.\d+\.\d+)\.txt")
_LINE = re.compile(r"^([0-9A-F]{4,6})(?:\.\.([0-9A-F]{4,6}))?\s*;\s*(\w+)")
# Unassigned, private-use, surrogate, and noncharacter code points all have
# the Script value Unknown, which Scripts.txt leaves implicit.
_UNKNOWN = "Unknown"


def parse(text: str) -> tuple[str, list[str]]:
    """Return the Unicode version and the script name of each BMP code point."""
    match = _VERSION.match(text)
    if match is None:
        msg = "not a Scripts.txt file: no version line"
        raise ValueError(msg)
    scripts = [_UNKNOWN] * _BMP_END
    for line in text.splitlines():
        entry = _LINE.match(line)
        if entry is None:
            continue
        first = int(entry.group(1), 16)
        last = int(entry.group(2) or entry.group(1), 16)
        for code_point in range(first, min(last, _BMP_END - 1) + 1):
            scripts[code_point] = entry.group(3)
    return match.group(1), scripts


def render(version: str, scripts: list[str]) -> str:
    """Render the module source for *scripts*."""
    names = [_UNKNOWN, *sorted(set(scripts) - {_UNKNOWN})]
    index = {name: i for i, name in enumerate(names)}
    runs: list[tuple[int, int]] = []
    for code_point, name in enumerate(scripts):
        if not runs or runs[-1][1] != index[name]:
            runs.append((code_point, index[name]))
    lines = [
        '"""The Unicode Script property of every BMP code point.',
        "",
        "Generated by ``scripts/generate_unicode_scripts.py`` from the Unicode",
        f"{version} ``Scripts.txt``.  Do not edit by hand.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        f'UNICODE_VERSION = "{version}"',
        "",
        "# Script names; ``BMP_SCRIPT_RUNS`` refers to them by index.  ``Unknown``",
        "# covers unassigned, private-use, surrogate, and noncharacter code points.",
        "SCRIPTS: tuple[str, ...] = (",
        *(f'    "{name}",' for name in names),
        ")",
        "",
        "# (first code point, index into SCRIPTS).  A run reaches to the code",
        "# point before the next entry, and the last one to U+FFFF.",
        "BMP_SCRIPT_RUNS: tuple[tuple[int, int], ...] = (",
        *(f"    (0x{first:04X}, {script})," for first, script in runs),
        ")",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    """Write the generated module to stdout."""
    version, scripts = parse(Path(sys.argv[1]).read_text(encoding="utf-8"))
    sys.stdout.write(render(version, scripts))


if __name__ == "__main__":
    main()
