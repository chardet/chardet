#!/usr/bin/env python
"""Generate ``scripts/quotation_marks.py`` from CLDR's ``delimiters.json``.

The table gives each trained language's quotation marks, which
``typography.restyle`` uses to set a share of the training text the way a
word processor in that language would.  It comes from one pinned CLDR
release, so a retrain does not depend on what a machine has installed.

Usage::

    git clone --depth 1 --branch 48.0.0 \
        https://github.com/unicode-org/cldr-json
    uv run python scripts/generate_quotation_marks.py \
        cldr-json/cldr-json/cldr-misc-full > scripts/quotation_marks.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from chardet.registry import REGISTRY

_FIELDS = (
    "quotationStart",
    "quotationEnd",
    "alternateQuotationStart",
    "alternateQuotationEnd",
)


def trained_languages() -> list[str]:
    """Return every language the registry trains a model for."""
    return sorted({lang for info in REGISTRY.values() for lang in info.languages})


def parse(package_dir: Path, languages: list[str]) -> tuple[str, dict[str, list[str]]]:
    """Return the CLDR version and each language's four quotation marks."""
    package = json.loads((package_dir / "package.json").read_text(encoding="utf-8"))
    marks: dict[str, list[str]] = {}
    for language in languages:
        path = package_dir / "main" / language / "delimiters.json"
        if not path.is_file():
            continue
        data = json.loads(path.read_text(encoding="utf-8"))
        delimiters = data["main"][language]["delimiters"]
        marks[language] = [delimiters[field] for field in _FIELDS]
    return package["version"], marks


def render(version: str, marks: dict[str, list[str]]) -> str:
    """Render the module source for *marks*."""
    lines = [
        '"""Each trained language\'s quotation marks.',
        "",
        "Generated by ``scripts/generate_quotation_marks.py`` from the CLDR",
        f"{version} ``delimiters.json`` files.  Do not edit by hand.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        f'CLDR_VERSION = "{version}"',
        "",
        "# language -> (quotationStart, quotationEnd, alternateQuotationStart,",
        "# alternateQuotationEnd)",
        "QUOTATION_MARKS: dict[str, tuple[str, str, str, str]] = {",
    ]
    for language, quartet in sorted(marks.items()):
        escaped = ", ".join(f'"{_escape(mark)}"' for mark in quartet)
        lines.append(f'    "{language}": ({escaped}),')
    lines.append("}")
    return "\n".join(lines) + "\n"


def _escape(mark: str) -> str:
    return "".join(f"\\u{ord(ch):04x}" for ch in mark)


def main() -> None:
    """Write the generated module to standard output."""
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    version, marks = parse(Path(sys.argv[1]), trained_languages())
    sys.stdout.write(render(version, marks))


if __name__ == "__main__":
    main()
